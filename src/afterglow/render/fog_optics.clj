(ns afterglow.render.fog-optics
  "Beer–Lambert attenuation along one segment. Density is equivalent fog volume
  per cubic metre of room air. Extinction is per metre at unit density."
  (:require [afterglow.render.blocks :as blocks]
            [afterglow.render.fog-law :as fog-law]
            [afterglow.render.ir :as ir]
            [clojure.string :as str]))

(def ^:private parameters [:extinction :density :distance])

(defn- material-expression [constructor]
  (apply constructor (map (fn [parameter] {:op :param :key parameter}) parameters)))

(def ^:private depth-expression (material-expression blocks/fog-optical-depth-expression))

(def ^:private transmission-expression (material-expression blocks/fog-transmission-expression))

(defn- finite ^double [^double value]
  (if (Double/isFinite value)
    value
    (throw (ex-info "Fog optics requires finite inputs and optical depth" {:value value}))))

(defn- nonnegative ^double [^double value] (max 0.0 (finite value)))

(defn optical-depth ^double [^double extinction ^double density ^double distance]
  (finite (fog-law/optical-depth nonnegative * extinction density distance)))

(defn absorptance
  "Fraction removed from a direct ray. expm1 resolves trace haze even when its
  transmission would round to 1.0 on the host."
  ^double [^double depth]
  (- (Math/expm1 (- depth))))

(defn transmittance ^double [^double depth]
  (Math/exp (- depth)))

(defn- local-expression [material]
  (let [{:keys [uniforms expression]} (ir/emit-glsl material)
        names (into {} (map (fn [[parameter binding]] [(:name binding) (name parameter)])) uniforms)]
    (str/replace expression #"\bu_param_\d+\b" names)))

(defn browser-module
  "Emit the closed fog material as a static ES module. CPU and fragment shader
  use the same expression, with no dynamic shader or JavaScript evaluation."
  []
  (let [source (local-expression transmission-expression)
        depth (local-expression depth-expression)]
    (str "// Generated by afterglow.render.fog-optics from :optics/fog-transmission.\n"
         "const {exp, max} = Math;\n\n"
         "export function fogTransmission(extinction, density, distance) {\n"
         "  return " source ";\n}\n\n"
         "export function fogAbsorptance(extinction, density, distance) {\n"
         "  return -Math.expm1(-" depth ");\n}\n\n"
         "export const fogTransmissionGLSL = `float fogTransmission(float extinction, float density, float distance) {\n"
         "  return " source ";\n}`;\n")))

(defn -main [& [output]]
  (if output (spit output (browser-module)) (print (browser-module))))
